func validateSalavatResult(r AIResult) error {
	first, _, _ := strings.Cut(strings.TrimSpace(r.Body), "\n")
	if len([]rune(first)) > 120 || !strings.Contains(r.Body, "\n\n") || !(strings.Contains(r.Body, "#Вкоманде") || strings.Contains(r.Body, "#ГордостьКомпании") || strings.Contains(r.Body, "#ПроизводствоСС")) {
		return errors.New("Материал не прошёл проверку фирменного оформления: нужен короткий хук, абзацы и фирменный хештег. Повторите генерацию")
	}
	if strings.Contains(r.Body, "**") || strings.Contains(r.Body, "<b>") {
		return errors.New("Материал содержит служебную разметку вместо готового текста. Повторите генерацию")
	}
	return nil
}
